"""Pull the creator's notes-only descriptions straight from the Apotheosis notes (they win every clash).

Writes docs/hub/create/notes-text.js: the first paragraph of each Carlislean Lycanthrope feature
(Appendix III) and of each religion (Alignment & belief), with LaTeX markup removed. Religions the
notes haven't written up yet get nothing, so the creator shows only their alignment.
  python tools/creator/notes_text.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = [ROOT / "notes/sections/08-appendices/03-carlislean-lycanthrope-monster-class.tex",
       ROOT / "notes/sections/03-religions/01-alignment-belief.tex"]


def plain(t):
    t = re.sub(r"%.*", "", t)
    t = re.sub(r"\\begin\{(figure|table|center)\}.*?\\end\{\1\}", "", t, flags=re.S)
    for _ in range(4):
        t = re.sub(r"\\(?:textbf|textit|emph|textsc|underline|text)\{([^{}]*)\}", r"\1", t)
    t = t.replace("\\&", "&").replace("~", " ").replace("\\\\", " ").replace("--", "–")
    t = re.sub(r"\\[a-zA-Z]+\*?(\[[^\]]*\])?", "", t).replace("{", "").replace("}", "")
    return re.sub(r"\s+", " ", t).strip()


def main():
    out = {}
    for f in SRC:
        tex = f.read_text(encoding="utf-8")
        for m in re.finditer(r"\\subsection\*?\{([^}]+)\}(.*?)(?=\\(?:sub)*section|\Z)", tex, re.S):
            name = plain(m.group(1))
            paras = [plain(p) for p in re.split(r"\n\s*\n", m.group(2))]
            paras = [p for p in paras if len(p) > 20]
            if name and paras and name != "Class Features":
                out[name] = paras[0]
    js = ("// Generated by tools/creator/notes_text.py from the Apotheosis notes. Do not edit by hand.\n"
          f"window.CreatorNotesText = {json.dumps(out, ensure_ascii=False, indent=1)};\n")
    (ROOT / "docs/hub/create/notes-text.js").write_text(js, encoding="utf-8")
    print(len(out), "entries:", ", ".join(out))


if __name__ == "__main__":
    main()
